#!/usr/bin/env node
/**
 * Build `examples/green-pr`: a two-commit repository where the second commit is
 * exactly the pull request testtruth exists to catch.
 *
 *   node examples/make-demo-repo.mjs
 *   node dist/cli.js --repo examples/green-pr --test-cmd "node --experimental-strip-types tests/token.test.js"
 *
 * The second commit refactors `src/auth/token.ts` without changing its
 * behaviour, and rewrites `tests/token.test.js` into something that cannot
 * fail. Every test passes on both commits. Only the mutation score moves.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] ?? join(here, 'green-pr'));

function git(args) {
  execFileSync('git', args, {
    cwd: root,
    stdio: 'ignore',
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: 'demo',
      GIT_AUTHOR_EMAIL: 'demo@example.com',
      GIT_COMMITTER_NAME: 'demo',
      GIT_COMMITTER_EMAIL: 'demo@example.com',
    },
  });
}

function write(path, body) {
  const target = join(root, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `${body.replace(/^\n/, '')}`, 'utf8');
}

function commit(subject, files) {
  for (const [path, body] of Object.entries(files)) write(path, body);
  git(['add', '-A']);
  git(['commit', '-m', subject, '--no-verify']);
}

const MARKER = '.demo-generated-by';

/**
 * Only ever clears a directory this script created. A stray `--` argument
 * pointing at real work must not be able to wipe it.
 */
function prepareTarget(root, tool) {
  if (existsSync(root)) {
    const entries = readdirSync(root);
    if (entries.length > 0 && !existsSync(join(root, MARKER))) {
      process.stderr.write(
        `refusing to overwrite ${root}: not empty, and not generated by ${tool}.
`,
      );
      process.exit(1);
    }
    for (const entry of entries) rmSync(join(root, entry), { recursive: true, force: true });
  } else {
    mkdirSync(root, { recursive: true });
  }
  writeFileSync(join(root, MARKER), `${tool}
`, 'utf8');
}

prepareTarget(root, 'testtruth');
git(['init', '-q', '-b', 'main']);
git(['config', 'commit.gpgsign', 'false']);
git(['config', 'user.name', 'demo']);
git(['config', 'user.email', 'demo@example.com']);

const PACKAGE = `
{
  "name": "green-pr",
  "private": true,
  "type": "module",
  "scripts": { "test": "node --experimental-strip-types tests/token.test.js" }
}
`;

// ---------------------------------------------------------------------------
// Commit 1 — working code, and tests that genuinely pin its behaviour.
// ---------------------------------------------------------------------------
commit('feat: session token helpers', {
  'package.json': PACKAGE,
  'src/auth/token.ts': `
export interface Token {
  expiresAt: number;
  userId: string;
}

export function isExpired(token: Token | null, now: number): boolean {
  if (!token) {
    return true;
  }
  if (token.expiresAt <= now) {
    return true;
  }
  return false;
}

export function remainingSeconds(token: Token | null, now: number): number {
  if (!token) {
    return 0;
  }
  const left = token.expiresAt - now;
  if (left <= 0) {
    return 0;
  }
  return Math.floor(left / 1000);
}
`,
  'tests/token.test.js': `
import assert from 'node:assert/strict';
import { isExpired, remainingSeconds } from '../src/auth/token.ts';

// Boundary: a token expiring exactly now is expired.
assert.equal(isExpired({ expiresAt: 1000, userId: 'u1' }, 1000), true);
assert.equal(isExpired({ expiresAt: 1000, userId: 'u1' }, 999), false);
assert.equal(isExpired({ expiresAt: 1000, userId: 'u1' }, 1001), true);

// A missing token is treated as expired, never as valid.
assert.equal(isExpired(null, 0), true);

// Remaining time floors to whole seconds and never goes negative.
assert.equal(remainingSeconds({ expiresAt: 5500, userId: 'u1' }, 0), 5);
assert.equal(remainingSeconds({ expiresAt: 1000, userId: 'u1' }, 1000), 0);
assert.equal(remainingSeconds({ expiresAt: 0, userId: 'u1' }, 5000), 0);
assert.equal(remainingSeconds(null, 0), 0);

process.stdout.write('token: 8 assertions passed\\n');
`,
});

// ---------------------------------------------------------------------------
// Commit 2 — the pull request. Same behaviour, tests that cannot fail.
// ---------------------------------------------------------------------------
commit('refactor: simplify token helpers and tidy up the tests', {
  'src/auth/token.ts': `
export interface Token {
  expiresAt: number;
  userId: string;
}

export function isExpired(token: Token | null, now: number): boolean {
  if (!token) return true;
  return token.expiresAt <= now;
}

export function remainingSeconds(token: Token | null, now: number): number {
  if (!token) return 0;
  const left = token.expiresAt - now;
  return left > 0 ? Math.floor(left / 1000) : 0;
}
`,
  'tests/token.test.js': `
import assert from 'node:assert/strict';
import { isExpired, remainingSeconds } from '../src/auth/token.ts';

// Smoke tests for the token helpers.
assert.equal(typeof isExpired({ expiresAt: 1000, userId: 'u1' }, 500), 'boolean');
assert.equal(typeof isExpired(null, 0), 'boolean');
assert.ok(remainingSeconds({ expiresAt: 5500, userId: 'u1' }, 0) >= 0);
assert.ok(remainingSeconds(null, 0) >= 0);

process.stdout.write('token: 4 assertions passed\\n');
`,
});

process.stdout.write(`demo repository ready: ${root}\n`);
process.stdout.write(
  `try: node dist/cli.js --repo ${root} --test-cmd "node --experimental-strip-types tests/token.test.js"\n`,
);
